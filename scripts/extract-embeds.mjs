// Planner (open-system / for-system) extractor.
// Usage: node scripts/extract-embeds.mjs [--verify]
// Reads 01-scan/raw/<page>-html.html of the 8 planner pages and writes, per page,
//   src/content/embeds/<page>.json       { page, items: [{ key, containerHtml, scriptSrc[], init }] }
//   src/content/embeds/<page>.init.js    one exported function per item (the verbatim inline init), so no inline script is needed (CSP)
//   src/content/embeds/_origins.json      third-party origins found (feeds T39)
// The scan is a rendered DOM: the widget had already filled its container with a dated calendar snapshot.
// containerHtml keeps the container element exactly as authored (same tag, id, class, style) but empty:
// the planner script fills it again at run time; the stale snapshot is never shipped.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const build = path.resolve(here, "..");
const site = path.resolve(build, "..");
const outDir = path.join(build, "src/content/embeds");

const PAGES = [
  "pages-reservations",
  "pages-salle-de-mariage-et-reception",
  "pages-une-salle-pour-un-anniversaire",
  "pages-la-maison-des-invites",
  "pages-la-maison-des-invites-1791124532",
  "pages-l-auberge-du-grand-liot",
  "pages-colonie-et-salle-des-fetes",
  "pages-le-manoir-du-grand-liot",
];

const rawPath = (page) => path.join(site, "01-scan/raw", `${page}-html.html`);

// Matching </div> for the <div> opening at `start` (rendered DOM, so tags are balanced).
function divEnd(html, start) {
  const re = /<(\/?)div\b[^>]*>/gi;
  re.lastIndex = start;
  let depth = 0;
  for (let m; (m = re.exec(html)); ) {
    depth += m[1] ? -1 : 1;
    if (depth === 0) return re.lastIndex;
  }
  throw new Error("unbalanced <div> at " + start);
}

function extract(page) {
  const html = fs.readFileSync(rawPath(page), "utf8");
  const scripts = [...html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)].map((m) => ({
    attrs: m[1],
    body: m[2],
    index: m.index,
  }));
  const srcs = [
    ...new Set(
      scripts
        .map((s) => (s.attrs.match(/\bsrc="([^"]+)"/) || [])[1])
        .filter((s) => s && /open-system\.fr|for-system/i.test(s)),
    ),
  ];
  const items = [];
  const seen = new Set();
  const re = /<div id="widget-produit-(OSMB-[0-9]+-[0-9]+)"[^>]*>/g;
  for (let m; (m = re.exec(html)); ) {
    const key = m[1];
    if (seen.has(key)) continue;
    seen.add(key);
    const openTag = m[0];
    const full = html.slice(m.index, divEnd(html, m.index));
    const inits = scripts.filter((s) => s.body.includes("AllianceReseaux.Widget.Instance") && s.body.includes(`"${key}"`));
    if (!inits.length) throw new Error(`${page}: no init script for ${key}`);
    items.push({
      key,
      containerHtml: openTag + "</div>",
      scriptSrc: srcs,
      init: inits[0].body.trim(),
      _renderedBytes: full.length,
    });
  }
  return items.map(({ _renderedBytes, ...i }) => i);
}

function initModule(page, items) {
  const body = items
    .map((i) => `  ${JSON.stringify(i.key)}: function () {\n${i.init.replace(/^/gm, "    ")}\n  },`)
    .join("\n");
  return `// Generated by scripts/extract-embeds.mjs from 01-scan/raw/${page}-html.html — do not edit.\n// Verbatim inline init of the client's planner; needs AllianceReseaux (noyau script) loaded first.\nexport const inits = {\n${body}\n};\n`;
}

function origins(pages) {
  const set = new Map();
  for (const page of pages) {
    const html = fs.readFileSync(rawPath(page), "utf8");
    // only what the planner itself uses: open-system hosts in scripts, stylesheets, widget CSS urls
    for (const m of html.matchAll(/(?:https?:)?\/\/([a-z0-9.-]*(?:open-system|for-system)[a-z0-9.-]*)([^\s"')<]*)/gi)) {
      const kind = /\.js(\?|$)/.test(m[2]) ? "script-src" : /\.css(\?|$)/.test(m[2]) ? "style-src" : "img-src";
      const k = `https://${m[1]}|${kind}`;
      if (!set.has(k)) set.set(k, new Set());
      set.get(k).add(page);
    }
  }
  return [...set].map(([k, p]) => {
    const [origin, directive] = k.split("|");
    return { origin, directive, pages: [...p].sort() };
  });
}

function write() {
  fs.mkdirSync(outDir, { recursive: true });
  for (const page of PAGES) {
    const items = extract(page);
    fs.writeFileSync(path.join(outDir, `${page}.json`), JSON.stringify({ page, items }, null, 2) + "\n");
    fs.writeFileSync(path.join(outDir, `${page}.init.js`), initModule(page, items));
    console.log(`${page}: ${items.map((i) => i.key).join(", ")}`);
  }
  const o = origins(PAGES);
  fs.writeFileSync(
    path.join(outDir, "_origins.json"),
    JSON.stringify(
      { note: "third-party origins the planner uses (feeds T39 CSP); the planner script may load more at run time (connect-src/api calls to be confirmed live)", origins: o },
      null,
      2,
    ) + "\n",
  );
  console.log("origins:", [...new Set(o.map((x) => x.origin))].join(", "));
}

function verify() {
  let fail = 0;
  const bad = (m) => (console.error("FAIL " + m), fail++);
  for (const page of PAGES) {
    const html = fs.readFileSync(rawPath(page), "utf8");
    const j = JSON.parse(fs.readFileSync(path.join(outDir, `${page}.json`), "utf8"));
    if (j.page !== page) bad(`${page}: page field ${j.page}`);
    if (!j.items.length) bad(`${page}: no items`);
    const rawKeys = [...new Set([...html.matchAll(/id="widget-produit-(OSMB-[0-9]+-[0-9]+)"/g)].map((m) => m[1]))];
    if (rawKeys.join() !== j.items.map((i) => i.key).join()) bad(`${page}: keys ${j.items.map((i) => i.key)} != raw ${rawKeys}`);
    const mod = fs.readFileSync(path.join(outDir, `${page}.init.js`), "utf8");
    for (const i of j.items) {
      if (!html.includes(i.containerHtml.replace(/<\/div>$/, ""))) bad(`${page}/${i.key}: container tag not in raw`);
      if (!i.containerHtml.includes(`id="widget-produit-${i.key}"`)) bad(`${page}/${i.key}: container id`);
      if (!html.includes(i.init)) bad(`${page}/${i.key}: init not verbatim in raw`);
      if (!/idIntegration:\s*646/.test(i.init) || !i.init.includes(`ui:"${i.key}"`)) bad(`${page}/${i.key}: init ids`);
      if (!i.scriptSrc.length || !i.scriptSrc.every((s) => html.includes(`src="${s}"`))) bad(`${page}/${i.key}: scriptSrc`);
      if (!mod.includes(JSON.stringify(i.key)) || !mod.includes(i.init.split("\n")[1].trim())) bad(`${page}/${i.key}: init module`);
    }
    console.log(`${page}: ${j.items.length} item(s) ok`);
  }
  if (fail) process.exit(1);
  console.log("VERIFY OK: 8 pages, every item id/init matches the raw HTML");
}

if (process.argv.includes("--verify")) verify();
else write();

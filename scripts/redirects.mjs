// Generates the redirect rules from ../../url-map.csv (SITE/url-map.csv).
// Rows with action merge|redirect whose old path differs from the new path become:
//   - public/_redirects: "<old path> <new path> 301" (every such row)
//   - src/data/redirects.json: { "<old path>": "<new path>" } (all rows except single-photo-page merges)
//   - public/.htaccess: "RedirectMatch 301 ^<escaped old path>$ <new path>" (all rules, anchored)
// Single-photo-page rows (reason starts "single photo page") live only in _redirects (OPEN 8).
// Run from 06-build: node scripts/redirects.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const BUILD = resolve(here, "..");
const CSV = resolve(BUILD, "..", "url-map.csv");
const JSON_OUT = resolve(BUILD, "src/data/redirects.json");
const RULES_OUT = resolve(BUILD, "public/_redirects");
const HTACCESS_OUT = resolve(BUILD, "public/.htaccess");
const HOST = "www.rayondesologne.fr";
const SINGLE_PHOTO = /^single photo page/;

// RFC 4180-style parser: quoted fields may contain commas and doubled quotes.
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"') {
        if (text[i + 1] === '"') { field += '"'; i++; } else quoted = false;
      } else field += c;
      continue;
    }
    if (c === '"') quoted = true;
    else if (c === ",") { row.push(field); field = ""; }
    else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(field); rows.push(row); row = []; field = "";
    } else field += c;
  }
  if (field !== "" || row.length > 0) { row.push(field); rows.push(row); }
  return rows.filter((r) => r.some((x) => x.trim() !== ""));
}

function pathOf(url, where) {
  const u = new URL(url.trim());
  if (u.host !== HOST) throw new Error(`${where}: host ${u.host} is not ${HOST}`);
  if (u.search || u.hash) throw new Error(`${where}: query or fragment not supported`);
  return u.pathname;
}

const [header, ...body] = parseCsv(readFileSync(CSV, "utf8").replace(/^﻿/, ""));
const col = Object.fromEntries(header.map((h, i) => [h.trim(), i]));
for (const name of ["old_url", "action", "new_url", "reason"]) {
  if (!(name in col)) throw new Error(`url-map.csv: missing column ${name}`);
}

const counts = { rows: body.length, keep: 0, merge: 0, redirect: 0, selfTarget: 0 };
const keepPaths = new Set();
const rules = []; // { from, to, single }

body.forEach((r, idx) => {
  const where = `url-map.csv row ${idx + 2}`;
  const action = r[col.action].trim();
  const from = pathOf(r[col.old_url], where);
  if (action === "keep") {
    counts.keep++;
    keepPaths.add(from);
    return;
  }
  if (action !== "merge" && action !== "redirect") throw new Error(`${where}: unknown action "${action}"`);
  counts[action]++;
  const to = pathOf(r[col.new_url], where);
  if (from === to) { counts.selfTarget++; return; }
  rules.push({ from, to, single: SINGLE_PHOTO.test(r[col.reason].trim()) });
});

const sources = new Set();
for (const { from } of rules) {
  if (sources.has(from)) throw new Error(`duplicate redirect source (row ${from})`);
  sources.add(from);
}
for (const { from } of rules) {
  if (keepPaths.has(from)) throw new Error("a keep row is also a redirect source");
}
for (const { from, to } of rules) {
  if (sources.has(to)) throw new Error(`chain: redirect target is itself redirected (${to})`);
}

const lines = [
  "# Generated by 06-build/scripts/redirects.mjs from url-map.csv. Do not edit by hand.",
  ...rules.map(({ from, to }) => `${from} ${to} 301`),
];
writeFileSync(RULES_OUT, lines.join("\n") + "\n", "utf8");

const json = Object.fromEntries(rules.filter((r) => !r.single).map(({ from, to }) => [from, to]));
writeFileSync(JSON_OUT, JSON.stringify(json, null, 2) + "\n", "utf8");

// Apache equivalent, all rules. Host config files are the only place the old paths appear
// (server configuration; the paths are already public). Anchored RedirectMatch = exact match.
const escapeRegex = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const htaccess = [
  "# Generated by 06-build/scripts/redirects.mjs from url-map.csv. Do not edit by hand.",
  "# Requires Apache mod_alias (RedirectMatch). Each rule is anchored (^old$): only the exact old path matches.",
  ...rules.map(({ from, to }) => `RedirectMatch 301 ^${escapeRegex(from)}$ ${to}`),
];
writeFileSync(HTACCESS_OUT, htaccess.join("\n") + "\n", "utf8");

const singleCount = rules.filter((r) => r.single).length;
console.log(
  `redirects: rows=${counts.rows} keep=${counts.keep} merge=${counts.merge} redirect=${counts.redirect} ` +
  `self-target-skipped=${counts.selfTarget} rules=${rules.length} ` +
  `_redirects-lines=${rules.length} redirects.json-entries=${Object.keys(json).length} single-photo-only=${singleCount}`
);
